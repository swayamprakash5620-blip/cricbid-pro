function makeStats(opts: {
  ipl?: [number, number, number, number, number, number, string];
  t20i?: [number, number, number, number, number, number, string];
  odi?: [number, number, number, number, number, number, string];
  test?: [number, number, number, number, number, number, string];
}) {
  const mapLine = (arr?: [number, number, number, number, number, number, string]) =>
    arr
      ? {
          matches: arr[0],
          runs: arr[1],
          average: arr[2],
          strikeRate: arr[3],
          wickets: arr[4],
          economy: arr[5],
          best: arr[6],
        }
      : undefined;

  return {
    ipl: mapLine(opts.ipl),
    t20i: mapLine(opts.t20i),
    odi: mapLine(opts.odi),
    test: mapLine(opts.test),
  };
}

