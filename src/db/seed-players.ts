// Combined roster: core stars + extended current international & IPL players (deduped by slug)
export const ALL_PLAYERS_SEED: PlayerSnapshot[] = (() => {
  const seen = new Set<string>();
  const out: PlayerSnapshot[] = [];
  for (const p of [...INITIAL_PLAYERS_SEED, ...EXTENDED_PLAYERS_SEED, ...EXTRA_PLAYERS_SEED]) {
    if (seen.has(p.slug)) continue;
    seen.add(p.slug);
    out.push(p);
  }
  return out;
})();

interface LiveStatsEntry {
  stats: PlayerFormatStats;
  formats: Exclude<CricketFormat, "ALL">[];
  profile: PlayerProfile;
  battingStyle?: string;
  bowlingStyle?: string;
  role?: PlayerRole;
  franchiseTag?: string;
  isCapped?: boolean;
}
const LIVE = liveStats as unknown as { players: Record<string, LiveStatsEntry>; rulesVersion?: string };
const LIVE_VERSION = LIVE.rulesVersion ?? "2026.3";

function roleToSet(role: PlayerRole, bowlingStyle: string, current: PlayerSetCategory): PlayerSetCategory {
  if (role === "Batsman") return "Batsmen";
  if (role === "Wicketkeeper") return "Wicketkeepers";
  if (role === "All-Rounder") return "All-Rounders";
  if (current === "Fast Bowlers" || current === "Spinners") return current;
  return /spin|break|orthodox|googly|leg|off/i.test(bowlingStyle) ? "Spinners" : "Fast Bowlers";
}

/** Applies live 2026 stats (Wikipedia + Cricsheet) to the players table and refreshes room snapshots. */
async function applyLiveStats() {
  const rows = await db
    .select({
      id: players.id,
      slug: players.slug,
      role: players.role,
      setCategory: players.setCategory,
      isMarquee: players.isMarquee,
      isCapped: players.isCapped,
      bowlingStyle: players.bowlingStyle,
      profile: players.profile,
    })
    .from(players);

  let updated = 0;
  for (const r of rows) {
    const live = LIVE.players[r.slug];
    if (!live || r.profile?.dataVersion === LIVE_VERSION) continue;
    const role = live.role ?? r.role;
    const bowlingStyle = live.bowlingStyle ?? r.bowlingStyle;
    const isCapped = live.isCapped ?? r.isCapped;
    let setCategory = r.setCategory;
    if (!r.isMarquee) {
      setCategory = !isCapped ? "Uncapped" : roleToSet(role, bowlingStyle, r.setCategory === "Uncapped" ? "Batsmen" : r.setCategory);
    }
    await db
      .update(players)
      .set({
        stats: live.stats,
        formats: live.formats,
        profile: { ...live.profile, dataVersion: LIVE_VERSION },
        role,
        bowlingStyle,
        battingStyle: live.battingStyle ?? undefined,
        franchiseTag: live.franchiseTag ?? undefined,
        isCapped,
        setCategory,
      })
      .where(eq(players.id, r.id));
    updated++;
  }

  if (updated > 0) {
    // Refresh the player copies stored inside every auction room
    await db.execute(sql`
      UPDATE room_players rp
      SET custom_player_snapshot = rp.custom_player_snapshot || jsonb_build_object(
        'stats', p.stats,
        'formats', p.formats,
        'profile', p.profile,
        'role', p.role,
        'battingStyle', p.batting_style,
        'bowlingStyle', p.bowling_style,
        'franchiseTag', p.franchise_tag,
        'isCapped', p.is_capped,
        'setCategory', p.set_category
      )
      FROM players p
      WHERE rp.player_id = p.id
    `);
  }
  return updated;
}

let seedPromise: Promise<void> | null = null;
let seededVersion: string | null = null;

export async function ensurePlayersSeeded(): Promise<void> {
  if (seededVersion === LIVE_VERSION) return;
  if (seedPromise) {
    return seedPromise;
  }

  seedPromise = (async () => {
    try {
      const [{ total }] = await db.select({ total: count() }).from(players);
      const existingSlugs = new Set(
        total > 0
          ? (await db.select({ slug: players.slug }).from(players)).map((r) => r.slug)
          : []
      );
      const missing = ALL_PLAYERS_SEED.filter((p) => !existingSlugs.has(p.slug));
      const CHUNK = 50;
      for (let i = 0; i < missing.length; i += CHUNK) {
        const batch = missing.slice(i, i + CHUNK);
        await db
          .insert(players)
          .values(batch.map((item) => ({
            slug: item.slug,
            name: item.name,
            country: item.country,
            isOverseasDefault: item.isOverseasDefault,
            role: item.role,
            battingStyle: item.battingStyle,
            bowlingStyle: item.bowlingStyle,
            setCategory: item.setCategory,
            isCapped: item.isCapped,
            isMarquee: item.isMarquee,
            basePriceLakhs: item.basePriceLakhs,
            franchiseTag: item.franchiseTag,
            formats: item.formats,
            stats: item.stats,
            rating: item.rating,
          })))
          .onConflictDoNothing({ target: players.slug });
      }
      await applyLiveStats();
      seededVersion = LIVE_VERSION;
    } finally {
      seedPromise = null;
    }
  })();

  return seedPromise;
}
